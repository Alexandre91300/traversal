const TABLES: Record<Lang, Record<Key, string>> = { en, fr }

function detect(): Lang {
  try {
    const saved = localStorage.getItem('traversal.lang')
    if (saved === 'en' || saved === 'fr') return saved
  } catch { /* storage blocked: fall through */ }
  return navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

let lang: Lang = detect()
document.documentElement.lang = lang
const listeners = new Set<() => void>()

export function setLang(next: Lang) {
  lang = next
  try { localStorage.setItem('traversal.lang', next) } catch { /* per-viewer convenience only */ }
  document.documentElement.lang = next
  listeners.forEach(f => f())
}

const subscribe = (f: () => void) => {
  listeners.add(f)
  return () => listeners.delete(f)
}

export const useLang = (): Lang => useSyncExternalStore(subscribe, () => lang)

export function translate(l: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = TABLES[l][key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

export type T = (key: Key, vars?: Record<string, string | number>) => string

export function useT(): T {
  const l = useLang()
  return useCallback((key, vars) => translate(l, key, vars), [l])
}

// Picks the current language from a bilingual value (Lesson text).
export function useText() {
  const l = useLang()
  return useCallback((t: Text) => t[l], [l])
}
